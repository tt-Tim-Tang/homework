/***************************************************************************
  函数名称：
  功    能：
  输入参数：
  返 回 值：
  说    明：只给出了上下标尺，其它均需要自己补充
***************************************************************************/
int main()
{
	int n;
	cout << "请输入要打印的行数[3..13]" << endl;
	cin >> n;
	/* 上标尺 */
	cout << "--------------------------------------------------------------------------------" << endl;
	cout << "0         1         2         3         4         5         6         7" << endl;
	cout << "01234567890123456789012345678901234567890123456789012345678901234567890123456789" << endl;
	cout << "--------------------------------------------------------------------------------" << endl;
	int a[13][13] = { 0 };
	for (int i = 0; i < 13; i++) {
		a[i][0] = 1;
		a[i][i] = 1;
	}
	for (int i = 2; i < n; i++) {
		for (int j = 1; j < i; j++) {
			a[i][j] = a[i - 1][j - 1] + a[i - 1][j];
		}
	}
	for (int i = 0; i < n; i++) {
		for (int j = n - 1; j >= 0; j--) {
			if (a[i][j]==0) {
				cout << setw(6) << " ";
			}
			else {
				cout << setw(6) << a[i][j];
			}
		}
		cout << endl;
	}

	/* 下标尺 */
	cout << "--------------------------------------------------------------------------------" << endl;
	cout << "01234567890123456789012345678901234567890123456789012345678901234567890123456789" << endl;
	cout << "0         1         2         3         4         5         6         7" << endl;
	cout << "--------------------------------------------------------------------------------" << endl;
	cout << endl;

	return 0;
}